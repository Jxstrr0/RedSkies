/* =====================================================================
   RED SKIES — models_blender.js   Blender-built aircraft (V1.8)
   Turns RS.blenderData (models_blender_data.js, generated by tools/blender/build_models.py) into three.js models and
   hooks them into the Models API in place of the box placeholders: 'drone', 'helo_attack', 'transport'.
   Same rules as the other model files: metres, +Z forward, +Y up, origin near the centre of mass.
   opts.lod 'low' picks the decimated copy. The spinning part is a child named 'rotor' (scene.js turns it around its
   local Y axis); the drone's propeller sits in a holder that stands that axis along the fuselage.
   Paint and ambient occlusion are baked into vertex colours, so one material draws the whole airframe.
   If the data is missing or broken, the placeholder is used instead.
   ===================================================================== */
(function () {
  const RS = window.RS;
  const KINDS = ['drone', 'helo_attack', 'transport'];
  const geo = {};                                                  // kind|lod|part -> BufferGeometry (shared by every clone)
  let mats = null;

  function bytes(b64) {
    const s = atob(b64), n = s.length, u = new Uint8Array(n);
    for (let i = 0; i < n; i++) u[i] = s.charCodeAt(i);
    return u;
  }
  function materials() {
    if (mats) return mats;
    const D = THREE.DoubleSide;
    mats = {
      paint: new THREE.MeshStandardMaterial({ color: 0xffffff, vertexColors: true, roughness: 0.8, metalness: 0.08, side: D }),
      glass: new THREE.MeshStandardMaterial({ color: 0xffffff, vertexColors: true, roughness: 0.12, metalness: 0.85, side: D })
    };
    return mats;
  }
  function geometry(kind, lod, name, part, ext) {
    const key = kind + '|' + lod + '|' + name;
    if (geo[key]) return geo[key];
    const pu = bytes(part.p), p16 = new Int16Array(pu.buffer, 0, part.n * 3), q8 = new Int8Array(bytes(part.q).buffer, 0, part.n * 3), c8 = bytes(part.c);
    const pos = new Float32Array(part.n * 3), nor = new Float32Array(part.n * 3), col = new Float32Array(part.n * 3), k = ext / 32767;
    // the game renders without an output colour conversion, so the stored colours are used as they are (like the hex colours of the other models)
    for (let i = 0; i < part.n * 3; i++) { pos[i] = p16[i] * k; nor[i] = q8[i] / 127; col[i] = c8[i] / 255; }
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
    g.setAttribute('normal', new THREE.BufferAttribute(nor, 3));
    g.setAttribute('color', new THREE.BufferAttribute(col, 3));
    g.setIndex(new THREE.BufferAttribute(new Uint16Array(bytes(part.i).buffer, 0, part.t * 3), 1));
    g.computeBoundingSphere();
    return (geo[key] = g);
  }

  function create(kind, opts) {
    const D = RS.blenderData && RS.blenderData[kind];
    if (!D) return null;
    const lod = opts && opts.lod === 'low' ? 'low' : 'high', L = D[lod] || D.high, M = materials();
    const g = new THREE.Group(); g.name = kind;
    let rotor = null;
    for (const name of Object.keys(L.parts)) {
      const part = L.parts[name], mesh = new THREE.Mesh(geometry(kind, lod, name, part, L.ext), name === 'glass' ? M.glass : M.paint);
      mesh.name = name === 'rotor' ? 'rotor_mesh' : name;
      if (name !== 'rotor') { g.add(mesh); continue; }
      // the spinning part: scene.js spins the node called 'rotor' around its local Y
      rotor = new THREE.Group(); rotor.name = 'rotor';
      const pv = part.pivot || [0, 0, 0];
      if (part.axis === 'f') {                                      // propeller: spin axis along the fuselage
        const holder = new THREE.Group(); holder.name = 'rotor_holder';
        holder.position.set(pv[0], pv[1], pv[2]); holder.rotation.x = Math.PI / 2;
        mesh.rotation.x = -Math.PI / 2;
        rotor.add(mesh); holder.add(rotor); g.add(holder);
      } else { rotor.position.set(pv[0], pv[1], pv[2]); rotor.add(mesh); g.add(rotor); }
    }
    g.userData = { kind, length: D.length, rotor, nozzles: null, source: 'blender' };
    return g;
  }

  let M = (typeof Models !== 'undefined') ? Models : window.Models; // eslint-disable-line no-undef
  if (!M || !RS.blenderData) return;
  const prev = typeof M.create === 'function' ? M.create.bind(M) : null;
  M.create = function (kind, opts) {
    if (KINDS.indexOf(kind) >= 0 && !(opts && opts.primitive)) {
      try { const o = create(kind, opts); if (o) return o; } catch (e) { console.warn('RS.models: ' + kind + ' Blender model failed, using placeholder', e); }
    }
    return prev ? prev(kind, opts) : null;
  };
  M.blender = { kinds: KINDS.slice(), create };
  M.version = (M.version || '0') + '+blender-1.0';
})();
